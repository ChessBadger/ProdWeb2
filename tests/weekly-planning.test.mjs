import assert from 'node:assert/strict';
import vm from 'node:vm';
import {createPlannerContext,initializeData} from '../scripts/planner-context.mjs';
const c=createPlannerContext(),run=s=>vm.runInContext(s,c),plain=x=>JSON.parse(JSON.stringify(x));
const raw={Employee:1,AccountName:'A',StoreName:'S',DateOfInv:'2025-01-01',Expr1:4,Total_Ext_Qty:400,PiecesPerHr:100,SupervisorNumber:99};
c.raw=raw;
assert.equal(run('normalizeRow({...raw,AVG_DELTA:null}).isModas'),null);
assert.equal(run('normalizeRow({...raw,AVG_DELTA:""}).isModas'),null);
assert.equal(run('normalizeRow({...raw,AVG_DELTA:"bad"}).isModas'),null);
assert.equal(run('normalizeRow({...raw,AVG_DELTA:0}).isModas'),false);
assert.equal(run('normalizeRow({...raw,AVG_DELTA:1}).isModas'),true);
assert.equal(run('buildJobs([normalizeRow({...raw,AVG_DELTA:null}),normalizeRow({...raw,Employee:2,AVG_DELTA:0})])[0].inventoryMode'),null);
assert.equal(run('inferWeight({manHours:0,totalExtQty:10000})'),0);
const rows=Array.from({length:120},(_,i)=>({...raw,DateOfInv:new Date(Date.UTC(2025,0,1+i)).toISOString().slice(0,10),Expr1:4+i%3/10,AVG_DELTA:1}));
initializeData(c,JSON.stringify({sheet:rows}));
c.before=await run('buildDurationReplayRecords(state.rows,state.jobs)');
const original=run('DurationModel.analyze(before,state.jobs)');
assert.ok(original.validationEnd<original.calibrationStart);
assert.ok(original.calibrationStart<original.testMetrics.splitDate);
assert.equal(c.DurationModel.weekStart(original.testMetrics.splitDate),original.testMetrics.splitDate);
const target=c.before.find(r=>r.date==='2025-04-18');
initializeData(c,JSON.stringify({sheet:rows.map(r=>r.DateOfInv>='2025-04-14'&&r.DateOfInv<'2025-04-18'?{...r,Expr1:99,PiecesPerHr:999999}:r)}));
const after=await run('buildDurationReplayRecords(state.rows,state.jobs)');
assert.deepEqual(plain(after.find(r=>r.date===target.date).input),plain(target.input),'earlier days of same week must not leak into Friday');
initializeData(c,JSON.stringify({sheet:rows.map(r=>r.DateOfInv>=original.testMetrics.splitDate?{...r,Expr1:100}:r)}));
c.changed=await run('buildDurationReplayRecords(state.rows,state.jobs)');
const changed=run('DurationModel.analyze(changed,state.jobs)');
assert.deepEqual(plain(changed.config),plain(original.config));
assert.deepEqual(plain(changed.errorGlobal),plain(original.errorGlobal),'later test outcomes cannot calibrate uncertainty');
initializeData(c,JSON.stringify({EmployeeProductionHistory:[raw,{...raw,Employee:2}],_meta:{latestEmployeeIds:['2']}}));
assert.deepEqual(plain(run('getSchedulableEmployeeIds()')),['2'],'retained employees are not automatically selectable');
console.log('Unknown telemetry, weekly leakage, separate calibration, and retained-history roster tests passed.');
c.fetch=async()=>({status:500,ok:false});
await assert.rejects(run('fetchHistoryJson()'),/refusing to silently discard/);
c.fetch=async()=>({status:200,ok:true,text:async()=>'{"bad":true}'});
await assert.rejects(run('fetchHistoryJson()'),/damaged or unsupported/);
let calls=0;
c.fetch=async()=>++calls===1?{status:404,ok:false}:{status:200,ok:true,text:async()=>JSON.stringify({sheet:[raw]})};
assert.equal((await run('fetchHistoryJson()')).payload.sheet.length,1);
assert.equal(calls,2);
console.log('History loading fails closed on damage and falls back only when absent.');
const M=c.DurationModel;
const sameDay=Array.from({length:25},(_,i)=>({date:'2025-01-01',duration:i+1,storeKey:`a||${i}`,accountKey:'a',typeOfInv:'X',inventoryMode:false,employees:['1']}));
const plan={date:'2025-02-01',storeKey:'new',accountKey:'a',typeOfInv:'X',inventoryMode:false,employees:['1'],roles:{}};
const pred=js=>M.predict(M.createHistory(js),plan,()=>({speed:100,known:true})).onSiteDuration;
assert.equal(pred(sameDay),pred([...sameDay].reverse()),'same-day fallback selection must not depend on export ordering');
console.log('Same-day store reference selection is deterministic.');
